        function setLanguage(lang) {
            const langEN = document.getElementById('langEN');
            const langKH = document.getElementById('langKH');

            if (lang === 'en') {
                langEN.className = 'text-gold-400 underline underline-offset-4';
                langKH.className = 'text-gray-400 hover:text-gold-400 transition-colors';
            } else {
                langKH.className = 'text-gold-400 underline underline-offset-4';
                langEN.className = 'text-gray-400 hover:text-gold-400 transition-colors';
            }

            document.querySelectorAll('[lang-key]').forEach(el => {
                const key = el.getAttribute('lang-key');
                if (translations[lang] && translations[lang][key]) {
                    el.innerText = translations[lang][key];
                }
            });
        }

