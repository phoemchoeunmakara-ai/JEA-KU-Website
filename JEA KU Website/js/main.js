        function postBlessing() {
            const name = document.getElementById('blessingName').value.trim();
            const text = document.getElementById('blessingText').value.trim();

            if (name && text) {
                const feed = document.getElementById('blessingFeed');
                const newCard = document.createElement('div');
                newCard.className = 'p-4 bg-sage-800/80 border border-gold-500/20';
                newCard.innerHTML = `
                    <div class="flex justify-between text-xs text-gold-400 mb-1">
                        <span class="font-bold">${name}</span>
                        <span class="text-[10px] text-gray-400">Just now</span>
                    </div>
                    <p class="text-xs text-ivory-100 font-light">${text}</p>
                `;
                feed.prepend(newCard);

                document.getElementById('blessingName').value = '';
                document.getElementById('blessingCouple').value = '';
                document.getElementById('blessingText').value = '';
                toggleBlessingInput();
            }
        }

