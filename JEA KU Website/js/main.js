        function switchQR(bank) {
            const abaBlock = document.getElementById('abaQRBlock');
            const wingBlock = document.getElementById('wingQRBlock');
            const btnABA = document.getElementById('btnABA');
            const btnWing = document.getElementById('btnWing');

            if (bank === 'aba') {
                abaBlock.classList.remove('hidden');
                wingBlock.classList.add('hidden');
                btnABA.className = 'flex-1 py-1.5 text-xs font-bold bg-sage-800 text-gold-300';
                btnWing.className = 'flex-1 py-1.5 text-xs font-bold text-sage-800';
            } else {
                abaBlock.classList.add('hidden');
                wingBlock.classList.remove('hidden');
                btnWing.className = 'flex-1 py-1.5 text-xs font-bold bg-sage-800 text-gold-300';
                btnABA.className = 'flex-1 py-1.5 text-xs font-bold text-sage-800';
            }
        }

        // --- 4. Portfolio Filter Logic ---
        function filterPortfolio(category) {
            const items = document.querySelectorAll('.port-item');
            const tabs = document.querySelectorAll('.port-tab');

            tabs.forEach(tab => {
                tab.classList.remove('bg-sage-800', 'text-gold-300', 'border-gold-500');
                tab.classList.add('bg-white', 'text-sage-800', 'border-ivory-300');
            });

            event.target.classList.remove('bg-white', 'text-sage-800', 'border-ivory-300');
            event.target.classList.add('bg-sage-800', 'text-gold-300', 'border-gold-500');

            items.forEach(item => {
                if (category === 'all' || item.classList.contains(category)) {
                    item.style.display = 'block';
                } else {
                    item.style.display = 'none';
                }
            });
        }

